"use strict";
// electron-builder afterPack hook (wired via "afterPack" in package.json "build").
// macOS: copies Electron's and Chromium's licence notices into the .app (addMacLicenceNotices).
// Linux: puts a small POSIX sh launcher in front of the Electron binary: the real binary becomes
// "<executable>.bin" and "<executable>" is the script. The /usr/bin link and the .desktop file of the
// .deb, the AppImage's AppRun and the .tar.gz all start "<executable>", so one script covers all of them.
//
// Why a script: Chromium decides about its sandbox (and aborts as root) before any app JavaScript runs,
// so main.js cannot fix that. The launcher:
//  - "--headless" or no graphical display: runs src/cli.js with Electron's built-in Node.js
//    (ELECTRON_RUN_AS_NODE), so no Chromium processes (sandbox, zygote, GPU) are started at all.
//    This is why the RunAsNode fuse stays enabled (package.json "electronFuses").
//  - otherwise: starts the desktop app with the Chromium sandbox ON whenever it can work. It is turned off
//    (ELECTRON_DISABLE_SANDBOX=1) only when it cannot: running as root, or no usable user namespaces
//    (kernel setting, container, or Ubuntu's AppArmor restriction for programs without a profile - the
//    .deb installs one) and no usable SUID chrome-sandbox helper (it cannot handle the space in
//    "/opt/OPC UA Simulator"). Then it prints one line and adds one line to the app's log file.
//    `--no-sandbox` / ELECTRON_DISABLE_SANDBOX=1 turn it off on request (e.g. in containers).
//  - checks for missing shared libraries first (minimal server / container images) and prints the
//    exact apt / dnf command instead of a bare "error while loading shared libraries" or SIGTRAP.
//
// Electron fuses: electron-builder flips them ("electronFuses" in package.json) right AFTER this hook on
// "<appOutDir>/<executable>", which by then is the launcher script. On Linux this hook therefore points
// the packager's fuse step at the real binary ("<executable>.bin") and checks the result.
const fs = require("fs");
const path = require("path");

const SANDBOX_DOC = "https://github.com/Manjuhombaradi/opcua-simulator/blob/main/SECURITY.md#linux-sandbox";

/** Quotes a value for use inside a double-quoted sh string. */
function shDq(value) {
    return String(value).replace(/[\\"$`]/g, "\\$&");
}

/**
 * Returns the launcher script.
 * binName: file name of the real Electron binary; cliPath: cli.js relative to the app folder;
 * productName: Electron's app name (its userData folder is ~/.config/<productName>);
 * profileName: name of the AppArmor profile the .deb installs (the executable name).
 */
function launcherScript({ binName, cliPath, productName, profileName }) {
    return `#!/bin/sh
# ${productName} launcher, generated by build/afterPack.js. The real Electron binary is ${binName}.
#   --headless (or no graphical display): headless simulator, runs with Electron's built-in Node.js
#   otherwise: desktop app, with the Chromium sandbox unless it cannot work here (see sandbox_problem)
SELF="$(readlink -f "$0" 2>/dev/null)"
[ -n "$SELF" ] || SELF="$0"
HERE="$(cd "$(dirname "$SELF")" && pwd -P)"
BIN="$HERE/${shDq(binName)}"

MODE=gui
NO_SANDBOX_ARG=""
for ARG in "$@"; do
    if [ "$ARG" = "--headless" ]; then MODE=headless; fi
    if [ "$ARG" = "--no-sandbox" ]; then NO_SANDBOX_ARG=1; fi
done
if [ "$MODE" = gui ] && [ -z "$DISPLAY" ] && [ -z "$WAYLAND_DISPLAY" ]; then
    echo "No graphical display found (DISPLAY / WAYLAND_DISPLAY not set) - starting ${shDq(productName)} in headless mode." >&2
    MODE=headless
fi

# true when a shared library can be found; dlopen()ed libraries do not show up in ldd
have_lib() {
    OLD_IFS="$IFS"; IFS=:
    for DIR in $LD_LIBRARY_PATH; do
        if [ -n "$DIR" ] && [ -e "$DIR/$1" ]; then IFS="$OLD_IFS"; return 0; fi
    done
    IFS="$OLD_IFS"
    for DIR in /usr/lib/*-linux-gnu /lib/*-linux-gnu /usr/lib64 /lib64 /usr/lib /lib /usr/local/lib; do
        if [ -e "$DIR/$1" ]; then return 0; fi
    done
    # /sbin is not in a normal user's PATH on Debian
    for LDCONFIG in ldconfig /sbin/ldconfig /usr/sbin/ldconfig; do
        if command -v "$LDCONFIG" >/dev/null 2>&1; then
            "$LDCONFIG" -p 2>/dev/null | grep -q "$1" && return 0
            break
        fi
    done
    return 1
}

# ALSA package name: libasound2t64 on Ubuntu 24.04+ / Debian 13+ (64-bit time_t transition)
alsa_package() {
    if command -v apt-cache >/dev/null 2>&1 && apt-cache show libasound2t64 >/dev/null 2>&1; then
        echo libasound2t64; return
    fi
    ID=""; VERSION_ID=""
    if [ -r /etc/os-release ]; then . /etc/os-release; fi
    case "$ID" in
        ubuntu) if [ "\${VERSION_ID%%.*}" -ge 24 ] 2>/dev/null; then echo libasound2t64; return; fi ;;
        debian) if [ "\${VERSION_ID%%.*}" -ge 13 ] 2>/dev/null; then echo libasound2t64; return; fi ;;
    esac
    echo libasound2
}

if command -v ldd >/dev/null 2>&1; then
    MISSING="$(ldd "$BIN" 2>/dev/null | sed -n 's/^[[:space:]]*\\([^[:space:]]*\\) => not found.*/\\1/p' | sort -u | tr '\\n' ' ')"
    if [ "$MODE" = gui ] && ! have_lib libX11-xcb.so.1; then MISSING="\${MISSING}libX11-xcb.so.1 "; fi
    if [ -n "$MISSING" ]; then
        # root (e.g. a minimal container) usually has no sudo
        SUDO="sudo "
        if [ "$(id -u)" = 0 ]; then SUDO=""; fi
        {
            echo "${shDq(productName)} cannot start, these system libraries are missing: $MISSING"
            echo "Install them and start again:"
            echo "  Debian/Ubuntu: \${SUDO}apt-get update && \${SUDO}apt-get install -y libgtk-3-0 libnss3 $(alsa_package) libgbm1 libx11-xcb1 libxss1 libxtst6 libatspi2.0-0 libsecret-1-0 libnotify4 xdg-utils"
            echo "  Fedora/RHEL:   \${SUDO}dnf install -y gtk3 nss alsa-lib mesa-libgbm libX11-xcb libXScrnSaver libXtst at-spi2-core libsecret libnotify xdg-utils"
        } >&2
        exit 1
    fi
fi

# the desktop app's data folder (Electron's userData); headless mode uses it too unless OPCUA_DATA_DIR / --data-dir say otherwise
if [ -z "$HOME" ]; then HOME="$(getent passwd "$(id -u)" 2>/dev/null | cut -d: -f6)"; fi
APP_DATA_DIR="\${XDG_CONFIG_HOME:-$HOME/.config}/${shDq(productName)}"

if [ "$MODE" = headless ]; then
    DATA_DIR="\${OPCUA_DATA_DIR:-$APP_DATA_DIR}"
    export ELECTRON_RUN_AS_NODE=1
    exec "$BIN" "$HERE/${shDq(cliPath)}" --data-dir "$DATA_DIR" "$@"
fi

# first line of a file; nothing when it cannot be read
first_line() {
    LINE=""
    if [ -r "$1" ]; then read -r LINE < "$1" 2>/dev/null; fi
    printf '%s' "$LINE"
}

# true when this launcher runs under the AppArmor profile the .deb installs (/etc/apparmor.d/${shDq(profileName)}):
# it allows user namespaces for ${shDq(binName)}, also where Ubuntu restricts them for other programs
under_own_apparmor_profile() {
    for ATTR in /proc/self/attr/apparmor/current /proc/self/attr/current; do
        LABEL="$(first_line "$ATTR")"
        case "$LABEL" in
            "${shDq(profileName)}"|"${shDq(profileName)} ("*) return 0 ;;
        esac
        if [ -n "$LABEL" ]; then return 1; fi
    done
    return 1
}

# true when chrome-sandbox can serve as Chromium's SUID fallback: owned by root with the setuid bit,
# and no space in the folder name (the helper cannot handle "/opt/OPC UA Simulator")
suid_helper_usable() {
    HELPER="$HERE/chrome-sandbox"
    case "$HERE" in *" "*) return 1 ;; esac
    if [ ! -u "$HELPER" ] || [ ! -x "$HELPER" ]; then return 1; fi
    [ "$(stat -c %u "$HELPER" 2>/dev/null || ls -ln "$HELPER" 2>/dev/null | awk '{print $3}')" = 0 ]
}

# Prints why the Chromium sandbox cannot be used; prints nothing when it can (the normal case).
sandbox_problem() {
    if [ -n "$NO_SANDBOX_ARG" ] || [ -n "\${ELECTRON_DISABLE_SANDBOX+set}" ]; then
        echo "turned off on request (--no-sandbox / ELECTRON_DISABLE_SANDBOX)"; return
    fi
    if [ "$(id -u)" = 0 ]; then
        echo "running as root (start the app as a normal user to keep it)"; return
    fi
    USERNS=yes
    if [ "$(first_line /proc/sys/kernel/unprivileged_userns_clone)" = 0 ] || [ "$(first_line /proc/sys/user/max_user_namespaces)" = 0 ]; then
        USERNS=no
    elif [ "$(first_line /proc/sys/kernel/apparmor_restrict_unprivileged_userns)" = 1 ]; then
        # Ubuntu 23.10+: only programs whose AppArmor profile allows it may use user namespaces
        under_own_apparmor_profile || USERNS=no
    elif ! command -v unshare >/dev/null 2>&1 || ! unshare -Ur true >/dev/null 2>&1; then
        USERNS=no
    fi
    if [ "$USERNS" = yes ] || suid_helper_usable; then return; fi
    echo "unprivileged user namespaces are not available (kernel setting, container or AppArmor restriction; the .deb package installs an AppArmor profile that allows them)"
}

unset ELECTRON_RUN_AS_NODE
SANDBOX_PROBLEM="$(sandbox_problem)"
if [ -n "$SANDBOX_PROBLEM" ]; then
    NOTE="Chromium sandbox disabled: $SANDBOX_PROBLEM. Details: ${SANDBOX_DOC}"
    echo "${shDq(productName)}: $NOTE" >&2
    # one line in the app's log file (logs/simulator.log in the data folder), private like the app's own files
    ( umask 077 && mkdir -p "$APP_DATA_DIR/logs" && printf '%s WARN  [launcher] %s\\n' "$(date -u +%Y-%m-%dT%H:%M:%S.000Z)" "$NOTE" >> "$APP_DATA_DIR/logs/simulator.log" ) 2>/dev/null
    # the reason, for the app's own log view
    export OPCUA_SANDBOX_NOTE="$NOTE"
    export ELECTRON_DISABLE_SANDBOX=1
fi
exec "$BIN" "$@"
`;
}

/** Loads @electron/fuses (a dependency of electron-builder's app-builder-lib). */
function loadFuses() {
    try {
        return require("@electron/fuses");
    } catch (_) {
        const builderLib = path.dirname(require.resolve("app-builder-lib/package.json"));
        return require(require.resolve("@electron/fuses", { paths: [builderLib] }));
    }
}

/**
 * Makes electron-builder's fuse step (configured by "electronFuses" in package.json, run right after
 * afterPack) flip the fuses of the real Electron binary instead of the launcher script, and verifies them.
 */
function redirectFusesToBinary(packager, binName) {
    if (packager.__opcuaFusesOnBinary) return;
    packager.__opcuaFusesOnBinary = true;
    packager.addElectronFuses = async (context, fuseConfig) => {
        const { flipFuses, getCurrentFuseWire, FuseV1Options } = loadFuses();
        const binPath = path.join(context.appOutDir, binName);
        await flipFuses(binPath, fuseConfig);
        const wire = await getCurrentFuseWire(binPath);
        const wrong = Object.keys(fuseConfig)
            .filter((key) => /^\d+$/.test(key) && typeof fuseConfig[key] === "boolean")
            .filter((key) => wire[key] !== (fuseConfig[key] ? 0x31 : 0x30))
            .map((key) => FuseV1Options[key] || key);
        if (wrong.length) throw new Error(`afterPack: Electron fuses not applied to ${binPath}: ${wrong.join(", ")}`);
        console.log(`  • afterPack: flipped Electron fuses on ${binPath}`);
    };
}

/**
 * macOS: the .dmg / .zip contain only the .app, while electron-builder leaves Electron's licence notices
 * next to it. Copy them into the app (Contents/Resources), as Windows and Linux builds already ship them.
 * LICENSES.chromium.html is in node_modules/electron/dist, which exists only once Electron's binary was
 * downloaded (npm start does that; CI installs with --ignore-scripts): if it is missing, Electron's own
 * installer downloads it (checked against the checksums in the electron package).
 */
function addMacLicenceNotices(context) {
    const resources = path.join(context.appOutDir, `${context.packager.appInfo.productFilename}.app`, "Contents", "Resources");
    const electronDir = path.dirname(require.resolve("electron/package.json"));
    const electronDist = path.join(electronDir, "dist");
    const notices = [["LICENSE", "LICENSE.electron.txt"], ["LICENSES.chromium.html", "LICENSES.chromium.html"]];
    const find = (from) => [path.join(context.appOutDir, from), path.join(electronDist, from)].find((file) => fs.existsSync(file));
    if (!notices.every(([from]) => find(from))) {
        console.log("  • afterPack: downloading Electron's binary once for its licence notices (node_modules/electron/install.js)");
        const result = require("child_process").spawnSync(process.execPath, [path.join(electronDir, "install.js")], { stdio: "inherit" });
        if (result.status !== 0) throw new Error("afterPack: could not download Electron for its licence notices (node node_modules/electron/install.js)");
    }
    for (const [from, to] of notices) {
        const source = find(from);
        if (!source) throw new Error(`afterPack: Electron licence notice ${from} not found in ${context.appOutDir} or ${electronDist}`);
        fs.copyFileSync(source, path.join(resources, to));
    }
    console.log(`  • afterPack: added Electron / Chromium licence notices to ${resources}`);
}

async function afterPack(context) {
    if (context.electronPlatformName === "darwin" || context.electronPlatformName === "mas") {
        addMacLicenceNotices(context);
        return;
    }
    if (context.electronPlatformName !== "linux") return;
    const appOutDir = context.appOutDir;
    const exeName = context.packager.executableName;
    const exePath = path.join(appOutDir, exeName);
    const binName = `${exeName}.bin`;
    const binPath = path.join(appOutDir, binName);

    // run once per output folder: do not move the script over the binary if the hook runs again
    const head = Buffer.alloc(2);
    const fd = fs.openSync(exePath, "r");
    try { fs.readSync(fd, head, 0, 2, 0); } finally { fs.closeSync(fd); }
    if (head.toString() !== "#!") fs.renameSync(exePath, binPath);
    if (!fs.existsSync(binPath)) throw new Error(`afterPack: Electron binary ${binPath} not found`);

    const asar = fs.existsSync(path.join(appOutDir, "resources", "app.asar"));
    const cliPath = `resources/${asar ? "app.asar" : "app"}/src/cli.js`;
    const productName = context.packager.appInfo.productName;
    fs.writeFileSync(exePath, launcherScript({ binName, cliPath, productName, profileName: exeName }), { mode: 0o755 });
    fs.chmodSync(exePath, 0o755);
    console.log(`  • afterPack: wrote Linux launcher ${exePath} (Electron binary: ${binName})`);

    if (context.packager.config && context.packager.config.electronFuses) redirectFusesToBinary(context.packager, binName);
}

module.exports = afterPack;
module.exports.afterPack = afterPack;
module.exports.launcherScript = launcherScript;
